notas = [7.5, 9.2, 5.0, 10.0, 8.4, 6]
print(notas)
a = len(notas) #Contar o numeros de itens dentro de uma lista ou String
print(a)

maior_nota = max(notas) #Retorna o maior valor dentro da array
print(maior_nota)
menor_nota = min(notas) #Retorna o menor valor dentro da array
print(menor_nota)
media = sum(notas) / len(notas) #Somo os valores dentro da array
print(f'{media:.2f}')

